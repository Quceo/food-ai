from ai import get_client #Взятие функции из другого файла

def get_recipes(products): #Функция для принятия строки с продуктами от пользователя
    client = get_client() #Подключение к API

    #Формируем промпт для нейросети
    prompt = f"""
    Ты — AI-помощник по приготовлению еды.
    Продукты пользователя: {products}
    Предложи ровно 3 блюда.
    Используй в первую очередь продукты пользователя.
    Если каких-то продуктов не хватает — укажи их отдельно.
    Верни ответ строго в JSON со следующими параметрами:
    блюда (список), название, ингредиенты (список), приготовление (список), недостающие_продукты (список).
    ОБЯЗАТЕЛЬНО сделай так, чтобы каждый из элементов был в формате элемента списка, а не в виде строки.
    """
    response = client.chat.completions.create(
        model="nvidia/nemotron-3.5-super-vl:free", # указываем какая нейросеть используется.........
        response_format={"type": "json_object"},  # заставляем вернуть именно JSON
        messages=[
            {
                "role": "user",
                "content": prompt
            }
        ]
    )

    return response.choices[0].message.content #Извлекаем из ответа только саму JSON-строку
